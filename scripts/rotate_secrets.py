def main():
    parser = argparse.ArgumentParser(description="Rotate AutoBiz Engine secrets")
    parser.add_argument(
        "--env-file",
        default=".env",
        help="Path to the .env file (default: .env)",
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Show what would change without modifying",
    )
    parser.add_argument(
        "--output",
        default=None,
        help="Write new secrets to a different file",
    )
    parser.add_argument(
        "--generate-template",
        action="store_true",
        help="Generate a .env.example template and exit",
    )

    args = parser.parse_args()

    if args.generate_template:
        print(generate_env_template())
        return

    rotate_secrets(args.env_file, dry_run=args.dry_run, output_file=args.output)


if __name__ == "__main__":
    main()
#!/usr/bin/env python3
"""
Secret Rotation Script
Rotates environment secrets and generates secure random values.
Usage: python scripts/rotate_secrets.py [--dry-run] [--output .env.new]
"""
import secrets
import string
import argparse
import os
import re
from datetime import datetime


def generate_secret(length: int = 32) -> str:
    """Generate a cryptographically secure random secret."""
    alphabet = string.ascii_letters + string.digits + "!@#$%^&*()_+-="
    return "".join(secrets.choice(alphabet) for _ in range(length))


def generate_uuid() -> str:
    """Generate a UUID v4."""
    import uuid
    return str(uuid.uuid4())


SECRETS_MAP = {
    "SECRET_KEY": lambda: generate_secret(64),
    "DATABASE_URL": None,  # Don't auto-rotate — requires manual update
    "OPENAI_API_KEY": None,  # Don't auto-rotate — requires manual input
    "ANTHROPIC_API_KEY": None,  # Don't auto-rotate
    "REDIS_URL": None,  # Don't auto-rotate
    "RESEND_API_KEY": None,  # Don't auto-rotate
    "SENDGRID_API_KEY": None,  # Don't auto-rotate
    "STRIPE_API_KEY": None,  # Don't auto-rotate
    "STRIPE_WEBHOOK_SECRET": lambda: generate_secret(32),
    "JWT_SECRET": lambda: generate_secret(64),
    "ENCRYPTION_KEY": lambda: generate_secret(32),
}


def rotate_secrets(env_file: str, dry_run: bool = False, output_file: str = None):
    """
    Rotate secrets in the .env file.

    Args:
        env_file: Path to the current .env file.
        dry_run: If True, only print what would change without modifying.
        output_file: If set, write new secrets to this file instead of overwriting.
    """
    if not os.path.exists(env_file):
        print(f"❌ File not found: {env_file}")
        print(f"   Create {env_file} with your current secrets first.")
        return

    with open(env_file, "r") as f:
        lines = f.readlines()

    timestamp = datetime.utcnow().strftime("%Y-%m-%d %H:%M:%S UTC")
    changes = []
    new_lines = []

    for line in lines:
        line = line.rstrip("\n")

        # Skip comments and empty lines
        if not line or line.startswith("#"):
            new_lines.append(line)
            continue

        # Parse KEY=VALUE
        match = re.match(r"^([A-Za-z_][A-Za-z0-9_]*)=(.*)", line)
        if not match:
            new_lines.append(line)
            continue

        key, _ = match.groups()

        if key in SECRETS_MAP and SECRETS_MAP[key] is not None:
            new_value = SECRETS_MAP[key]()
            new_lines.append(f"{key}={new_value}")
            changes.append(key)
            if dry_run:
                print(f"  🔄 {key}: would rotate")
        else:
            new_lines.append(line)

    if dry_run:
        print(f"\n📋 Dry run complete. {len(changes)} secrets would be rotated:")
        for key in changes:
            print(f"   - {key}")
        print("\nRun without --dry-run to apply changes.")
        return

    # Write output
    output_path = output_file or env_file
    with open(output_path, "w") as f:
        f.write("# Auto-generated by rotate_secrets.py\n")
        f.write(f"# Last rotated: {timestamp}\n")
        for line in new_lines:
            f.write(line + "\n")

    if output_file:
        print(f"✅ New secrets written to: {output_file}")
    else:
        print(f"✅ Secrets rotated in place: {env_file}")

    print(f"📝 Rotated {len(changes)} secrets:")
    for key in changes:
        print(f"   ✅ {key}")

    print("\n⚠️  IMPORTANT:")
    print("   - Update any services that use these secrets")
    print("   - Restart all containers after applying changes")
    print("   - Securely delete any old secret values")


